import { expect, test } from "@playwright/test";
const API = process.env.E2E_API_URL ?? "http://localhost:4000";

test("reception creates an interested person, reserves, records attendance and converts without losing identity", async ({ page }) => {
  const marker = await page.request.get(`${API}/__test/isolated`);
  expect((await marker.json()).isolated, "E2E must only run against the ephemeral fixture").toBe(true);
  const login = await page.request.post(`${API}/api/auth/login`, { data: { login: "admin@example.test", password: "LocalDemoOnly-1234" } });
  expect(login.ok()).toBe(true);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto("/admin/contacts");
  await expect(page.getByRole("heading", { name: "Contactos", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Agregar contacto", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Nuevo contacto" })).toBeVisible();
  const firstName = `Interesada ${Date.now()}`;
  await page.getByLabel("Nombre", { exact: true }).fill(firstName);
  await page.getByLabel("Apellido", { exact: true }).fill("Verificación");
  await page.getByLabel("Teléfono", { exact: true }).fill("2215551234");
  await page.getByLabel("DNI", { exact: true }).fill("31.234.567");
  await expect(page.getByRole("combobox", { name: "Sede", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Guardar contacto" }).click();
  await expect(page.getByRole("heading", { name: `${firstName} Verificación` })).toBeVisible();
  const id = page.url().split("/").at(-1);
  await expect(page.getByRole("heading", { name: "Historial de clases" })).toBeVisible();
  await page.getByRole("button", { name: "Reservar clase sin cargo" }).click();
  await page.getByRole("combobox", { name: "Clase y horario" }).selectOption({ index: 1 });
  await page.getByRole("button", { name: "Guardar reserva" }).click();
  await expect(page.getByRole("status")).toContainText("Reserva guardada");
  await expect(page.getByText("Prueba gratuita", { exact: false })).toBeVisible();
  const detail = await (await page.request.get(`${API}/api/admin/contacts/${id}`)).json();
  expect(detail.student).toBeNull();
  await page.getByRole("button", { name: "Registrar presente", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Presente registrado");
  await page.screenshot({ path: "../../artifacts/contacts-desktop.png", fullPage: true, animations: "disabled" });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "../../artifacts/contacts-mobile.png", fullPage: true, animations: "disabled" });
  expect(await page.locator("body").evaluate((body) => body.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByText("Más opciones").click();
  await page.getByRole("button", { name: "Generar credencial" }).click();
  await expect(page.getByRole("img", { name: `Credencial de aspirante de ${firstName} Verificación con QR de asistencia` })).toBeVisible();
  await page.screenshot({ path: "../../artifacts/credential-aspirante-mobile.png", fullPage: true, animations: "disabled" });
  const issuedBefore = (await (await page.request.get(`${API}/api/admin/check-in/contacts/${id}/credential`)).json()).issuedAt;
  expect(issuedBefore).toBeTruthy();
  await page.getByRole("button", { name: "Convertir en alumno" }).click();
  await page.getByRole("button", { name: "Confirmar conversión" }).click();
  await expect(page).toHaveURL(new RegExp(`/admin/students/${id}$`));
  const converted = await (await page.request.get(`${API}/api/admin/contacts/${id}`)).json();
  expect(converted.student._id).toBe(id);
  expect(converted.trials[0].consumedAt).toBeTruthy();
  const credentialAfter = await (await page.request.get(`${API}/api/admin/check-in/contacts/${id}/credential`)).json();
  expect(credentialAfter.active).toBe(true);
  expect(credentialAfter.issuedAt).toBe(issuedBefore);
  await page.getByRole("button", { name: /QR e historial/ }).click();
  await expect(page.getByRole("heading", { name: "Credencial de asistencia" })).toBeVisible();
  await expect(page.getByText("Prueba gratuita", { exact: false })).toBeVisible();
  await expect(page.getByRole("img", { name: `Credencial de alumno de ${firstName} Verificación sin QR visible` })).toBeVisible();
  await page.getByRole("button", { name: "Renovar credencial" }).click();
  await page.getByRole("button", { name: "Renovar", exact: true }).click();
  await expect(page.getByRole("img", { name: `Credencial de alumno de ${firstName} Verificación con QR de asistencia` })).toBeVisible();
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: "../../artifacts/student-unified-desktop.png", fullPage: true, animations: "disabled" });
  expect(await page.locator("body").evaluate((body) => body.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole("button", { name: /Recordatorios Vista previa/ }).click();
  await expect(page.getByRole("heading", { name: "Recordatorio para este alumno" })).toBeVisible();
  await expect(page.getByLabel("Vista previa del mensaje")).toBeVisible();
  await page.getByRole("button", { name: "Ver contacto y preferencias" }).click();
  await expect(page.getByRole("heading", { name: "Contacto y preferencias" })).toBeVisible();
  await expect(page.locator("#student-contact-settings")).toBeInViewport();
  await expect(page.getByRole("img", { name: `Credencial de alumno de ${firstName} Verificación con QR de asistencia` })).toBeVisible();
  await expect(page).toHaveURL(new RegExp(`/admin/students/${id}$`));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "../../artifacts/student-unified-mobile.png", fullPage: true, animations: "disabled" });
  expect(await page.locator("body").evaluate((body) => body.scrollWidth <= window.innerWidth)).toBe(true);
  await page.goto("/admin/contacts");
  await expect(page.getByRole("heading", { name: "Posibles alumnos" })).toBeVisible();
  await expect(page.getByText("Cargando contactos…")).toHaveCount(0);
  await expect(page.getByRole("link", { name: new RegExp(firstName) })).toHaveCount(0);
});
