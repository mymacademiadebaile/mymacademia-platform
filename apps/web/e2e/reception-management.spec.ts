import { expect, test } from "@playwright/test";
import { copyFile, readFile } from "node:fs/promises";
const API = process.env.E2E_API_URL ?? "http://localhost:4000";

test("admin issues and revokes tablet access, prints a QR and previews reminders with automatic delivery off", async ({ page }) => {
  expect((await (await page.request.get(`${API}/__test/isolated`)).json()).isolated).toBe(true);
  await page.request.post(`${API}/api/auth/login`, { data: { login: "admin@example.test", password: "LocalDemoOnly-1234" } });
  const contact = (await (await page.request.get(`${API}/api/admin/students?q=Lucía`)).json()).items[0];
  const account = await (await page.request.get(`${API}/api/admin/debt-reminders/students/${contact._id}/preview`)).json();
  if (account.balance.pendingCents === 0) await page.request.post(`${API}/api/admin/billing/charges`, { data: {
    studentId: contact._id, kind: "OTHER", period: "2026-10", concept: "Clase de verificación", amount: 5000, dueDate: "2026-10-23"
  } });
  await page.goto(`/admin/contacts/${contact._id}`);
  await page.getByText("Más opciones").click();
  await page.getByLabel("Email", { exact: true }).fill("lucia@example.test");
  await page.getByRole("button", { name: "Guardar preferencias" }).click();
  await expect(page.getByRole("status")).toContainText("Preferencias actualizadas");
  const generate = page.getByRole("button", { name: /^(Generar|Renovar) credencial$/ });
  await expect(generate).toBeEnabled();
  const renewing = await generate.textContent(); await generate.click();
  if (renewing?.includes("Renovar")) await page.getByRole("button", { name: "Renovar", exact: true }).click();
  await expect(page.getByRole("img", { name: "Credencial de alumno de Lucía Pérez con QR de asistencia" })).toBeVisible();
  await expect(page.getByText("ALUMNO", { exact: true })).toBeVisible();
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "Descargar credencial" }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toBe("mym-credencial-alumno.png");
  const png = await readFile(await download.path());
  expect(png.subarray(0, 8).toString("hex")).toBe("89504e470d0a1a0a");
  expect(png.readUInt32BE(16)).toBe(1712);
  expect(png.readUInt32BE(20)).toBe(1080);
  await copyFile(await download.path(), "../../artifacts/credential-download.png");
  await page.goto("/admin/reception");
  await page.getByRole("tab", { name: "Acceso de tablet" }).click();
  await page.getByRole("button", { name: /^(Generar|Renovar) código$/ }).click();
  const code = await page.locator("output").textContent();
  expect(code).toMatch(/^[A-Z2-9]{5}-[A-Z2-9]{5}$/);
  await expect(page.getByText("Código pendiente de activar")).toBeVisible();
  await page.goto("/asistencia");
  await page.getByLabel("Código de acceso").fill(code!);
  await page.getByRole("button", { name: "Activar registro" }).click();
  await expect(page.getByRole("button", { name: "Escanear QR" })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("button", { name: "Escanear QR" })).toBeVisible();
  expect((await page.request.post(`${API}/api/auth/login`, { data: { login: "admin@example.test", password: "LocalDemoOnly-1234" } })).ok()).toBe(true);
  await page.goto("/admin/reception");
  await page.getByRole("tab", { name: "Acceso de tablet" }).click();
  await expect(page.getByText("Autorizada", { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole("tab", { name: "Acceso de tablet" }).click();
  await expect(page.getByText("Autorizada", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Revocar accesos" }).click();
  await page.getByRole("button", { name: "Revocar acceso", exact: true }).click();
  await expect(page.getByText("Acceso revocado")).toBeVisible();
  await expect(page.getByText("No hay tablets autorizadas.", { exact: false })).toBeVisible();
  expect((await page.request.get(`${API}/api/check-in/device`)).status()).toBe(401);
  await page.reload();
  await page.getByRole("tab", { name: "Acceso de tablet" }).click();
  await expect(page.getByText("No hay tablets autorizadas.", { exact: false })).toBeVisible();
  await expect(page.getByText("Revocada", { exact: true }).first()).toBeVisible();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: "../../artifacts/reception-desktop.png", fullPage: true, animations: "disabled" });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  expect(await page.getByRole("combobox", { name: "Sede" }).evaluate((field) => field.getBoundingClientRect().height)).toBeLessThanOrEqual(60);
  await page.screenshot({ path: "../../artifacts/reception-mobile.png", fullPage: true, animations: "disabled" });
  expect(await page.locator("body").evaluate((body) => body.scrollWidth <= window.innerWidth)).toBe(true);
  await page.goto(`/admin/reminders?studentId=${contact._id}`);
  await expect(page.getByLabel("Habilitar envío programado")).not.toBeChecked();
  await expect(page.getByRole("button", { name: "Enviar recordatorio", exact: true })).toBeDisabled();
  await page.getByLabel("Habilitar recordatorios por email").check();
  await page.getByRole("button", { name: "Guardar configuración" }).click();
  await expect(page.getByRole("status")).toHaveText("Configuración guardada");
  await expect(page.getByLabel("Vista previa del mensaje")).toHaveValue(/Saldo pendiente:/);
  await expect(page.getByLabel("Habilitar envío programado")).not.toBeChecked();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: "../../artifacts/reminders-desktop.png", fullPage: true, animations: "disabled" });
  // The fixture points SMTP at localhost:1; this exercises failure/history without sending real mail.
  await page.getByRole("button", { name: "Enviar recordatorio", exact: true }).click();
  await page.getByRole("button", { name: "Enviar email", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "No pudimos confirmar el envío" })).toBeVisible();
  await expect(page.getByText("Envío no confirmado", { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: "../../artifacts/reminders-mobile.png", fullPage: true, animations: "disabled" });
  expect(await page.locator("body").evaluate((body) => body.scrollWidth <= window.innerWidth)).toBe(true);
});
